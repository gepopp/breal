    <h3>5.2 Processing on our server and by service providers</h3>
    <ul>
        <li>
            <strong>Hosting and server log files:</strong> The website is operated by a hosting provider
            ([name and registered office of the hosting provider to be added]). IP address, date and time, page requested,
            browser and operating system and the referrer URL are processed as technically necessary. Error logs of our
            application (with URL, IP address, browser identifier and referrer) are kept for 14 days.
        </li>
        <li>
            <strong>Contact form:</strong> Your details (name, e-mail address, telephone number, subject, message and, if
            applicable, property address and file attachments) are stored in our database, attachments in a private storage
            area at Hetzner Online GmbH. We send you a confirmation link by e-mail; we only process your request after you
            have confirmed it.
        </li>
        <li>
            <strong>E-mail delivery:</strong> We send confirmation and reply e-mails through the service provider Resend, Inc.,
            USA, as a processor. The e-mails contain a tracking pixel and trackable links with which we record delivery and
            opening; the content of sent e-mails is stored in our database for up to 360 days.
        </li>
        <li>
            <strong>LinkedIn posts:</strong> Our servers retrieve posts of our company profile through LinkedIn’s interface. No
            data of visitors is transmitted to LinkedIn in the process; only a click on a link takes you to LinkedIn.
        </li>
        <li>
            <strong>Property data:</strong> We transfer the data of the properties we offer to our server through the interface
            of our real estate software. No visitor data is transmitted in the process.
        </li>
        <li>
            <strong>Customer portal:</strong> The “Customer login” link leads to a separate portal (realonline.bereal-immobilien.at).
            The portal’s own notices apply to data you enter there.
        </li>
    </ul>

