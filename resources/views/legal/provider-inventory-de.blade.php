    <h3>5.2 Verarbeitung auf unserem Server und bei Dienstleistern</h3>
    <ul>
        <li>
            <strong>Hosting und Server-Log-Dateien:</strong> Die Website wird bei einem Hosting-Anbieter betrieben
            ([Name und Sitz des Hosting-Anbieters ergänzen]). Dabei werden technisch notwendig IP-Adresse, Datum und Uhrzeit,
            aufgerufene Seite, Browser und Betriebssystem sowie die Referrer-URL verarbeitet. Fehlerprotokolle unserer
            Anwendung (mit URL, IP-Adresse, Browserkennung und Referrer) werden 14 Tage aufbewahrt.
        </li>
        <li>
            <strong>Kontaktformular:</strong> Ihre Angaben (Name, E-Mail-Adresse, Telefonnummer, Betreff, Nachricht, bei Bedarf
            Objektadresse und Dateianhänge) werden in unserer Datenbank gespeichert, Anhänge in einem privaten Speicherbereich bei
            der Hetzner Online GmbH. Wir senden Ihnen einen Bestätigungslink per E-Mail; erst nach der Bestätigung bearbeiten wir
            Ihre Anfrage.
        </li>
        <li>
            <strong>E-Mail-Versand:</strong> Bestätigungs- und Antwort-E-Mails versenden wir über den Dienstleister Resend, Inc.,
            USA, als Auftragsverarbeiter. Die E-Mails enthalten ein Zählpixel und nachverfolgbare Links, mit denen wir Zustellung
            und Öffnung erfassen; die Inhalte versendeter E-Mails werden bis zu 360 Tage in unserer Datenbank gespeichert.
        </li>
        <li>
            <strong>LinkedIn-Beiträge:</strong> Beiträge unseres Unternehmensprofils rufen unsere Server über die Schnittstelle
            von LinkedIn ab. Dabei werden keine Daten von Besucherinnen und Besuchern an LinkedIn übermittelt; erst ein Klick auf
            einen Link führt zur Seite von LinkedIn.
        </li>
        <li>
            <strong>Objektdaten:</strong> Die Daten der angebotenen Immobilien übernehmen wir über die Schnittstelle unserer
            Immobilien-Software auf unseren Server. Besucherdaten werden dabei nicht übermittelt.
        </li>
        <li>
            <strong>Kundenportal:</strong> Der Link „Kundenlogin“ führt zu einem getrennten Portal (realonline.bereal-immobilien.at).
            Für Daten, die Sie dort eingeben, gelten die Hinweise des Portals.
        </li>
    </ul>

